    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        jalankan(s -> {
            Long id = idDipilih();
            Long riwayat = s.createQuery(
                    "select count(t) from TransaksiStok t where t.beras.id = :id", Long.class)
                    .setParameter("id", id).uniqueResult();
            if (riwayat != null && riwayat > 0) {
                throw new IllegalStateException("Beras ini sudah punya riwayat transaksi, tidak bisa dihapus.");
            }
            s.remove(s.get(Beras.class, id));
        });
    }//GEN-LAST:event_btnHapusActionPerformed

