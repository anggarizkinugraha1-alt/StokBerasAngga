    private DefaultTableModel model() {
        return (DefaultTableModel) tabel.getModel();
    }

    private Long idDipilih() {
        int r = tabel.getSelectedRow();
        if (r < 0) {
            throw new IllegalStateException("Pilih data di tabel dulu.");
        }
        return (Long) model().getValueAt(r, 0);
    }

    /** arah = 1 (barang masuk) atau -1 (barang keluar). */
    private void ubahStok(JComboBox<Beras> cmb, JSpinner jumlah, int arah) {
        jalankan(s -> {
            if (cmb.getSelectedItem() == null) {
                throw new IllegalStateException("Belum ada data beras.");
            }
            Beras b = s.get(Beras.class, ((Beras) cmb.getSelectedItem()).getId());
            int qty = (int) jumlah.getValue();
            int baru = b.getStok() + arah * qty;
            if (baru < 0) {
                throw new IllegalStateException("Stok tidak cukup. Stok sekarang " + b.getStok() + " kg.");
            }
            b.setStok(baru);
            // catat riwayat untuk laporan
            s.persist(new TransaksiStok(b, arah > 0 ? "MASUK" : "KELUAR", qty, LocalDateTime.now()));
        });
    }

    /** Menjalankan perubahan dalam satu transaksi, lalu memuat ulang tampilan. */
    private void jalankan(Consumer<Session> kerja) {
        try (Session s = HibernateUtil.getSessionFactory().openSession()) {
            Transaction t = s.beginTransaction();
            try {
                kerja.accept(s);
                t.commit();
            } catch (RuntimeException e) {
                t.rollback();
                throw e;
            }
            muat();
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Harga harus berupa angka.");
        } catch (RuntimeException e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }

    private void muat() {
        try (Session s = HibernateUtil.getSessionFactory().openSession()) {
            model().setRowCount(0);
            cmbMasuk.removeAllItems();
            cmbKeluar.removeAllItems();
            for (Beras b : s.createQuery("from Beras order by nama", Beras.class).list()) {
                model().addRow(new Object[]{b.getId(), b.getNama(), b.getHarga(), b.getStok()});
                cmbMasuk.addItem(b);
                cmbKeluar.addItem(b);
            }
        }
    }

    /** Laporan stok beras saat ini. */
    private void cetakLaporan() {
        try (Session s = HibernateUtil.getSessionFactory().openSession()) {
            tampilkan("/laporan_stok.jrxml", new HashMap<>(),
                    s.createQuery("from Beras order by nama", Beras.class).list());
        } catch (RuntimeException e) {
            JOptionPane.showMessageDialog(this, "Gagal membuat laporan: " + e.getMessage());
        }
    }

    /** Laporan beras masuk atau keluar; jenis = "MASUK" / "KELUAR". */
    private void cetakTransaksi(String jenis) {
        try (Session s = HibernateUtil.getSessionFactory().openSession()) {
            Map<String, Object> param = new HashMap<>();
            param.put("JUDUL", "LAPORAN BERAS " + jenis);
            tampilkan("/laporan_transaksi.jrxml", param, s.createQuery(
                    "select t from TransaksiStok t join fetch t.beras "
                    + "where t.jenis = :j order by t.tanggal desc", TransaksiStok.class)
                    .setParameter("j", jenis).list());
        } catch (RuntimeException e) {
            JOptionPane.showMessageDialog(this, "Gagal membuat laporan: " + e.getMessage());
        }
    }

    /** Compile template .jrxml, isi dengan data, lalu tampilkan di viewer. */
    private void tampilkan(String template, Map<String, Object> param, Collection<?> data) {
        try (InputStream in = getClass().getResourceAsStream(template)) {
            JasperReport report = JasperCompileManager.compileReport(in);
            JasperPrint print = JasperFillManager.fillReport(report, param, new JRBeanCollectionDataSource(data));
            JasperViewer.viewReport(print, false); // false = tutup viewer tidak menutup aplikasi
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal membuat laporan: " + e.getMessage());
        }
    }

